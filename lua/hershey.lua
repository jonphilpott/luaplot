--[[
    get_strokes(str, ox, oy, height)

    Returns strokes (list of polylines) positioned in drawing space, and
    total_advance (width of the rendered string in drawing units).

    Algorithm:
      1. Walk through each character of the string by its ASCII code.
      2. Look up the glyph data; skip characters with no glyph.
      3. Scale font coordinates: scale = height / CAP_HEIGHT
      4. Translate: draw_x = ox + cursor; draw_y = oy + hershey_y * scale
         Note: Hershey y is negative above baseline (e.g. -21 = cap top)
               and positive below (descenders). We keep Y-down convention:
               positive y goes DOWN on screen, so hershey_y is already
               in the right direction when mapped to screen y.
      5. Advance cursor by glyph.width * scale.
--]]
function M.get_strokes(str, ox, oy, height)
    local scale   = height / CAP_HEIGHT
    local cursor  = 0           -- horizontal pen position in font units
    local out     = {}          -- output: list of strokes

    for i = 1, #str do
        local code  = str:byte(i)
        local glyph = glyphs[code]
        if not glyph then goto next_char end

        local gwidth, gstrokes = glyph[1], glyph[2]

        for _, stroke in ipairs(gstrokes) do
            local pts = {}
            -- Each stroke is a list of {x, y} tables in font coordinates.
            for _, pt in ipairs(stroke) do
                local hx, hy = pt[1], pt[2]
                --[[
                    Coordinate mapping:
                    Hershey uses negative y above the baseline (-21 = cap top)
                    and positive y for descenders.  SVG/drawing space is Y-down,
                    so negative Hershey y correctly maps to a smaller draw y
                    (i.e. above oy).  No sign flip needed — just scale and offset.

                    draw_x = ox + (cursor_in_font_units + hershey_x) * scale
                    draw_y = oy + hershey_y * scale
                --]]
                local dx = ox + (cursor + hx) * scale
                local dy = oy + hy * scale
                table.insert(pts, {dx, dy})
            end
            if #pts >= 2 then
                table.insert(out, pts)
            end
        end

        cursor = cursor + gwidth

        ::next_char::
    end

    return out, cursor * scale   -- strokes, total pixel width
end

--[[
    measure(str, height)

    Returns the total advance width of str in drawing units, identical to
    the second return value of get_strokes() but without building any stroke
    geometry.  Use this whenever you need the width for layout purposes
    (centering, right-alignment, etc.) without actually drawing.
--]]
function M.measure(str, height)
    local scale  = height / CAP_HEIGHT
    local cursor = 0
    for i = 1, #str do
        local glyph = glyphs[str:byte(i)]
        if glyph then
            cursor = cursor + glyph[1]
        end
    end
    return cursor * scale
end

return M
