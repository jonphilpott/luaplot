--[[
    hershey.lua — single-stroke text using the Hershey Roman Simplex font

    The Hershey fonts are a set of single-stroke (pen-plotter friendly)
    typefaces developed by Dr. A. V. Hershey at the US Naval Weapons
    Laboratory in 1967 and placed in the public domain.

    Each character is encoded as a list of strokes.  Each stroke is a list
    of {x,y} points in a normalised coordinate system where:
        - The baseline sits at y = 0
        - Cap height is roughly 21 units
        - Characters are spaced using a per-character width value

    We store only printable ASCII 32–126.  Characters outside that range
    are silently skipped.

    ── Public API ────────────────────────────────────────────────────────────

    hershey.measure(str, height)
        Returns the advance width of str in drawing units without producing
        any stroke geometry.  Use this to calculate positions before drawing.

    hershey.get_strokes(str, ox, oy, height)
        Returns (strokes, total_advance):

        strokes       — list of strokes; each stroke is a list of {x,y}
                        points in drawing coordinates (already scaled and
                        positioned).  The caller draws each stroke as a
                        connected polyline with pen-up between strokes.

        total_advance — total width of the rendered string in drawing units,
                        useful for centering or chaining text calls.

        Parameters:
            str     — the string to render
            ox,oy   — drawing-space origin (top-left of the text block)
            height  — desired cap height in drawing units

    ── Coordinate transform ─────────────────────────────────────────────────

    Hershey units → drawing units:
        scale = height / CAP_HEIGHT
        draw_x = ox + (hershey_x * scale) + cursor_x_offset
        draw_y = oy + (hershey_y * scale)   -- Y-down: positive y goes down

    CAP_HEIGHT = 21 (empirical for Hershey Roman Simplex)
--]]

